def _grouped_horizontal_bars(
    row_labels: Sequence[str],
    series: Sequence[Tuple[str, Sequence[Optional[float]], str]],
    *,
    unit: str = "",
    aria_label: str = "",
    width: int = 680,
    value_digits: int = 2,
) -> str:
    """Render ``len(series)`` mini-clustered horizontal bars per row.

    ``series`` is a list of ``(series_label, values_per_row, color)``; every
    ``values_per_row`` sequence must have the same length as ``row_labels``
    (``None`` entries are skipped/rendered as zero-width). All series share
    one linear x-axis scaled to the largest value across every series, so
    bars remain visually comparable within one chart.
    """

    if not row_labels or not series:
        return ""
    label_w = 200
    plot_left = label_w
    plot_right = width - 90
    plot_w = max(10, plot_right - plot_left)
    sub_h = 14
    sub_gap = 3
    row_gap = 10
    row_h = len(series) * (sub_h + sub_gap) + row_gap
    margin_top = 10
    height = margin_top + len(row_labels) * row_h + 24

    all_values = [v for _, values, _ in series for v in values if v is not None]
    vmax = max(all_values) if all_values else 1.0
    if vmax <= 0:
        vmax = 1.0

    parts: List[str] = []
    for i, label in enumerate(row_labels):
        row_y = margin_top + i * row_h
        parts.append(
            f'<text x="{plot_left - 8}" y="{row_y + row_h / 2 + 4:.1f}" text-anchor="end" font-size="10">{esc(label)}</text>'
        )
        for j, (series_label, values, color) in enumerate(series):
            value = values[i] if i < len(values) else None
            sy = row_y + j * (sub_h + sub_gap)
            bw = 0.0 if value is None else max(1.5, plot_w * (value / vmax))
            value_text = NA if value is None else f"{value:.{value_digits}f}{unit}"
            title = f"{label} | {series_label}: {value_text}"
            parts.append(
                f'<rect x="{plot_left}" y="{sy:.1f}" width="{bw:.1f}" height="{sub_h}" fill="{color}">'
                f"<title>{esc(title)}</title></rect>"
            )
    axis_bottom = margin_top + len(row_labels) * row_h
    parts.append(
        f'<line class="axis" x1="{plot_left}" y1="{margin_top - 4}" x2="{plot_left}" y2="{axis_bottom + 4:.1f}" />'
    )
    parts.append(
        f'<line class="axis" x1="{plot_left}" y1="{axis_bottom + 4:.1f}" x2="{plot_right}" y2="{axis_bottom + 4:.1f}" />'
    )
    svg = (
        f'<svg class="chart bar-chart" viewBox="0 0 {width} {height}" role="img" '
        f'aria-label="{esc(aria_label)}">' + "".join(parts) + "</svg>"
    )
    legend = "".join(
        f'<li><span class="legend-dot" style="background:{color}"></span>{esc(series_label)}</li>'
        for series_label, _, color in series
    )
    return svg + f'<ul class="legend-list">{legend}</ul>'


def _stacked_segments(
    x: float, y: float, width: float, height: float, segments: Sequence[Tuple[float, str, str]]
) -> str:
    """Render one 100%-stacked horizontal bar. ``segments`` is a list of
    ``(value, fill, title)``; segments with a non-positive value are
    skipped. Returns an empty string if the total is not positive.
    """

    total = sum(v for v, _, _ in segments if v and v > 0)
    if total <= 0:
        return ""
    parts = []
    cx = x
    for value, fill, title in segments:
        if not value or value <= 0:
            continue
        seg_w = max(1.5, width * value / total)
        parts.append(
            f'<rect x="{cx:.1f}" y="{y:.1f}" width="{seg_w:.1f}" height="{height}" fill="{fill}" '
            f'stroke="#ffffff" stroke-width="0.6"><title>{esc(title)}</title></rect>'
        )
        cx += seg_w
    return "".join(parts)


