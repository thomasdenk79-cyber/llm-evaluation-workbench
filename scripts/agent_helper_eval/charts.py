def render_kpi_cards(aggregates: Sequence[AggregateRecord], samples: Sequence[SampleRecord]) -> str:
    """Render the executive-summary KPI card grid for one (usually the
    latest) campaign. Plain HTML, not SVG -- these are headline numbers,
    not a visualization, and should read correctly even with CSS disabled.

    Every "usable"/"excluded" split below reuses the exact same
    ``hard_gate_failed`` boolean as the leaderboard/excluded tables -- the
    hard rule (speed never compensates for unusable quality) is visible
    from the very first numbers a reader sees, not only deep in the
    per-campaign tables.
    """

    if not aggregates and not samples:
        return _no_data(
            "Keine Daten fuer Kennzahlen-Kacheln vorhanden.", "No data available for KPI cards."
        )
    usable = [a for a in aggregates if not a.hard_gate_failed]
    excluded = [a for a in aggregates if a.hard_gate_failed]
    total_samples = len(samples)
    accepted_samples = sum(1 for s in samples if s.acceptance_status == "accepted")
    acceptance_rate = (100.0 * accepted_samples / total_samples) if total_samples else None
    mean_tps = _mean([a.tokens_per_second_mean for a in usable])
    mean_success = _mean([a.success_rate_percent for a in usable])
    mean_ttar = _mean([a.time_to_accepted_result_seconds_mean for a in usable])

    def card(value: str, de: str, en: str, *, warn: bool = False) -> str:
        cls = "kpi-card kpi-card-warn" if warn else "kpi-card"
        return (
            f'<div class="{cls}"><div class="kpi-value">{esc(value)}</div>'
            f'<div class="kpi-label">{bi(de, en)}</div></div>'
        )

    cards = [
        card(str(len(aggregates)), "Modell-Laeufe gesamt", "Model-runs total"),
        card(
            f"{len(usable)}/{len(aggregates)}" if aggregates else NA,
            "Nutzbar (Akzeptanz-Gate bestanden)",
            "Usable (passed acceptance gate)",
        ),
        card(
            str(len(excluded)),
            "Ausgeschlossen (NICHT NUTZBAR)",
            "Excluded (NOT USABLE)",
            warn=bool(excluded),
        ),
        card(
            f"{accepted_samples}/{total_samples}" if total_samples else NA,
            "Akzeptierte Task-Versuche",
            "Accepted task attempts",
        ),
        card(
            f"{acceptance_rate:.1f}%" if acceptance_rate is not None else NA,
            "Akzeptanzquote (alle Versuche)",
            "Acceptance rate (all attempts)",
        ),
        card(
            f"{mean_success:.1f}%" if mean_success is not None else NA,
            "Ø Erfolgsquote (nutzbar)",
            "Avg success rate (usable)",
        ),
        card(
            f"{mean_tps:.2f}" if mean_tps is not None else NA,
            "Ø Tokens/s (nutzbar)",
            "Avg tokens/s (usable)",
        ),
        card(
            f"{mean_ttar:.2f}s" if mean_ttar is not None else NA,
            "Ø Zeit bis akzeptiertes Ergebnis (nutzbar)",
            "Avg time-to-accepted-result (usable)",
        ),
    ]
    return f'<div class="kpi-grid">{"".join(cards)}</div>'


