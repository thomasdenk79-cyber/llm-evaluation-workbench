# 15. Cost/routing scenario chart
# ---------------------------------------------------------------------------


def render_routing_scenario_chart(aggregates: Sequence[AggregateRecord], id_prefix: str = "") -> str:
    """Illustrative routing/cost-tier scenario: suitability-tier
    distribution among USABLE model-runs, grouped by ``provider`` as a
    cheap proxy for cost tier (local = no per-call cost, Siemens API =
    metered API cost, Copilot task-agent = subscription/seat cost). No
    fabricated dollar figures are used or displayed anywhere -- this
    chart only ever plots measured suitability-tier *counts*.

    Hard-gate-excluded model-runs are excluded from this routing view
    (matching the leaderboard): an orchestrator would never route work to
    a not-usable model regardless of its provider/cost tier, so including
    excluded runs here would misrepresent them as routing candidates.
    """

    usable = [a for a in aggregates if not a.hard_gate_failed]
    excluded = [a for a in aggregates if a.hard_gate_failed]
    if not usable:
        return (
            _no_data(
                "Keine nutzbaren Modell-Laeufe fuer das Routing-/Kostenszenario vorhanden.",
                "No usable model-runs available for the routing/cost scenario.",
            )
            + _excluded_ranking_note(excluded)
        )
    providers = sorted({a.provider for a in usable})
    width = 640
    label_w = 140
    bar_left = label_w
    bar_right = width - 90
    bar_w = bar_right - bar_left
    row_h = 34
    margin_top = 10
    height = margin_top + len(providers) * row_h + 20
    parts: List[str] = []
    for i, provider in enumerate(providers):
        rows = [a for a in usable if a.provider == provider]
        y = margin_top + i * row_h
        cy = y + row_h / 2
        parts.append(
            f'<text x="{bar_left - 8}" y="{cy + 4:.1f}" text-anchor="end" font-size="10">{esc(provider)}</text>'
        )
        counts: dict = {}
        for a in rows:
            counts[a.suitability_tier] = counts.get(a.suitability_tier, 0) + 1
        segments = [
            (float(count), TIER_COLORS.get(tier, "#718096"), f"{tier}: {count}/{len(rows)}")
            for tier, count in sorted(counts.items())
        ]
        parts.append(_stacked_segments(bar_left, y + 6, bar_w, row_h - 12, segments))
        parts.append(
            f'<text x="{bar_right + 6}" y="{cy + 4:.1f}" font-size="9">{esc(f"n={len(rows)}")}</text>'
        )
    svg = (
        f'<svg class="chart bar-chart" viewBox="0 0 {width} {height}" role="img" '
        f'aria-label="{esc("Eignungsverteilung je Anbieter (Routing-/Kosten-Szenario, illustrativ)")}">'
        + "".join(parts)
        + "</svg>"
    )
    legend_items = "".join(
        f'<li><span class="legend-dot" style="background:{color}"></span>{esc(tier)}</li>'
        for tier, color in TIER_COLORS.items()
    )
    caveat = (
        f'<p class="hint">{bi("Illustrativ: \'Anbieter\' dient hier nur als grobe Kosten-/Routing-Proxy-Kategorie (lokal = keine Kosten pro Aufruf, Siemens-API = abgerechnete API-Kosten, Copilot-Task-Agent = Abo-/Sitzplatzkosten). Es werden keine erfundenen Euro-/Dollar-Betraege gezeigt, nur gemessene Eignungsstufen-Verteilungen nutzbarer Modell-Laeufe.", "Illustrative: \'provider\' here is only a coarse cost/routing proxy category (local = no per-call cost, Siemens API = metered API cost, Copilot task-agent = subscription/seat cost). No fabricated dollar/euro figures are shown, only measured suitability-tier distributions of usable model-runs.")}</p>'
    )
    return svg + f'<ul class="legend-list">{legend_items}</ul>' + caveat + _excluded_ranking_note(excluded)


