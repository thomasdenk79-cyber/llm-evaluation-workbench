# 14. Measured-vs-projected RTX 5090 fit
# ---------------------------------------------------------------------------


def _feasibility_marker(x: float, cy: float, projection: Optional[FeasibilityProjection], *, allow_measured: bool, label: str) -> str:
    if projection is None:
        return f'<text x="{x:.1f}" y="{cy + 4:.1f}" font-size="10">{NA}</text>'
    confidence = projection.confidence
    if confidence == "measured" and not allow_measured:
        confidence = "projected"
    if projection.fits is True:
        color = TIER_COLORS["tier-1-recommended"]
        fits_word = "fits / passt"
    elif projection.fits is False:
        color = TIER_COLORS["tier-3-not-recommended"]
        fits_word = "does not fit / passt nicht"
    else:
        color = TIER_COLORS["insufficient-data"]
        fits_word = "unknown / unbekannt"
    title = f"{label}: {fits_word} ({confidence})"
    if confidence == "measured":
        return f'<circle cx="{x:.1f}" cy="{cy:.1f}" r="6" fill="{color}"><title>{esc(title)}</title></circle>'
    pts = f"{x:.1f},{cy - 7:.1f} {x + 7:.1f},{cy:.1f} {x:.1f},{cy + 7:.1f} {x - 7:.1f},{cy:.1f}"
    return (
        f'<polygon points="{pts}" fill="{color}" fill-opacity="0.55" stroke="{color}" '
        f'stroke-dasharray="2,2"><title>{esc(title)}</title></polygon>'
    )


def render_feasibility_fit_chart(specs: Sequence[ModelSpec], id_prefix: str = "") -> str:
    """Model-size-vs-VRAM-threshold chart: one row per model with a size
    bar plus two fit markers (12 GB owned hardware, hypothetical RTX 5090
    32 GB). Markers use BOTH shape and color to distinguish measured
    (solid circle) from projected/estimated (dashed diamond) -- a
    hypothetical 32 GB card can schema-never claim "measured", so its
    marker is always the dashed-diamond shape, never the solid circle,
    even defensively.
    """

    sized = [s for s in specs if s.size_gb_on_disk is not None]
    if not sized:
        return _no_data(
            "Keine Modellgroessendaten fuer die 5090-Passungs-Visualisierung vorhanden.",
            "No model size data available for the 5090 fit visualization.",
        )
    ordered = sorted(sized, key=lambda s: s.size_gb_on_disk)
    width = 700
    label_w = 190
    plot_left = label_w
    plot_right = width - 40
    plot_w = plot_right - plot_left
    row_h = 30
    margin_top = 34
    height = margin_top + len(ordered) * row_h + 30
    vmax = max(max(s.size_gb_on_disk for s in ordered), 32.0) * 1.15

    def x_pos(value: float) -> float:
        return plot_left + plot_w * (value / vmax)

    x12, x32 = x_pos(12.0), x_pos(32.0)
    plot_bottom = margin_top - 10 + len(ordered) * row_h + 10
    parts: List[str] = [
        f'<rect x="{plot_left}" y="{margin_top - 10}" width="{x12 - plot_left:.1f}" height="{plot_bottom - (margin_top - 10):.1f}" fill="{TIER_COLORS["tier-1-recommended"]}" fill-opacity="0.08"/>',
        f'<rect x="{x12:.1f}" y="{margin_top - 10}" width="{x32 - x12:.1f}" height="{plot_bottom - (margin_top - 10):.1f}" fill="{TIER_COLORS["tier-2-conditional"]}" fill-opacity="0.08"/>',
        f'<line x1="{x12:.1f}" y1="{margin_top - 10}" x2="{x12:.1f}" y2="{plot_bottom:.1f}" stroke="{TIER_COLORS["tier-1-recommended"]}" stroke-dasharray="4,3"/>',
        f'<text x="{x12:.1f}" y="{margin_top - 14}" text-anchor="middle" font-size="10">12 GB</text>',
        f'<line x1="{x32:.1f}" y1="{margin_top - 10}" x2="{x32:.1f}" y2="{plot_bottom:.1f}" stroke="{TIER_COLORS["tier-2-conditional"]}" stroke-dasharray="4,3"/>',
        f'<text x="{x32:.1f}" y="{margin_top - 14}" text-anchor="middle" font-size="9">32 GB (RTX 5090, hypothetisch/hypothetical)</text>',
    ]
    for i, spec in enumerate(ordered):
        y = margin_top + i * row_h
        cy = y + row_h / 2
        label = spec.display_name or f"{spec.provider}/{spec.backend}/{spec.model_id}"
        parts.append(
            f'<text x="{plot_left - 8}" y="{cy + 4:.1f}" text-anchor="end" font-size="10">{esc(label)}</text>'
        )
        bar_len = max(2.0, x_pos(spec.size_gb_on_disk) - plot_left)
        parts.append(
            f'<rect x="{plot_left}" y="{cy - 5:.1f}" width="{bar_len:.1f}" height="10" '
            f'fill="{TIER_COLORS["insufficient-data"]}" fill-opacity="0.5">'
            f'<title>{esc(f"{label}: {spec.size_gb_on_disk:.1f} GB on disk")}</title></rect>'
        )
        marker_x_12 = x_pos(spec.size_gb_on_disk) + 10
        marker_x_32 = marker_x_12 + 18
        parts.append(
            _feasibility_marker(
                marker_x_12, cy, spec.fits_12gb_vram, allow_measured=True, label=f"{label} @ 12 GB"
            )
        )
        parts.append(
            _feasibility_marker(
                marker_x_32,
                cy,
                spec.fits_rtx5090_32gb_projection,
                allow_measured=False,
                label=f"{label} @ RTX 5090 32 GB (hypothetisch/hypothetical)",
            )
        )
    svg = (
        f'<svg class="chart feasibility-chart" viewBox="0 0 {width} {height}" role="img" '
        f'aria-label="{esc("Modellgroesse vs. VRAM-Schwellen, gemessen vs. projiziert")}">' + "".join(parts) + "</svg>"
    )
    legend = (
        '<ul class="legend-list">'
        f'<li><span class="legend-dot" style="border-radius:50%;background:{TIER_COLORS["tier-1-recommended"]}"></span>{bi("Passt (Kreis = gemessen)", "Fits (circle = measured)")}</li>'
        f'<li><span class="legend-dot" style="border-radius:0;transform:rotate(45deg);background:{TIER_COLORS["tier-2-conditional"]}"></span>{bi("Raute gestrichelt = Projektion/Schaetzung (nie gemessen)", "Dashed diamond = projection/estimate (never measured)")}</li>'
        f'<li><span class="legend-dot" style="border-radius:50%;background:{TIER_COLORS["tier-3-not-recommended"]}"></span>{bi("Passt nicht", "Does not fit")}</li>'
        "</ul>"
    )
    caveat = (
        f'<p class="hint">{bi("Die hypothetische RTX 5090 32 GB kann laut Schema niemals als \'gemessen\' auftreten -- ihr Marker ist immer die gestrichelte Raute, nie der ausgefuellte Kreis.", "The hypothetical RTX 5090 32 GB can never be schema-validated as \'measured\' -- its marker is always the dashed diamond, never the solid circle.")}</p>'
    )
    return svg + legend + caveat


