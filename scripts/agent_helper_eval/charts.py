"""Dependency-free inline SVG chart renderers for the agent-helper HTML report.

Every function here returns a small, self-contained HTML fragment (one
``<svg class="chart" ...>`` plus an optional ``<ul class="legend-list">``
and/or bilingual caveat paragraph) -- never a reference to an external
charting library, font, or CDN asset, matching the offline-report
constraint in ``report.py``.

Design rules applied consistently across every chart in this module (see
``docs/project/agent_helper_benchmark.md`` for the full rationale):

- **Hard-acceptance-gate discipline.** Charts that compare or rank
  model-runs against each other (quality-vs-speed, latency percentiles,
  time-to-accepted-result, the routing/cost-tier scenario chart) NEVER plot
  a hard-gate-excluded ("not-usable") model-run alongside accepted ones --
  it is listed separately, in a distinctly worded warning note, exactly
  like the pre-existing quality-vs-speed chart. Speed/resource data must
  never make a not-usable model look like a plausible contender. Purely
  diagnostic/resource charts (critical-path, utilization ratios, CPU/GPU,
  RAM/VRAM, reliability, iteration/rework) instead show every model-run
  (matching the pre-existing resource/phase-timing *tables*, which are not
  ranking views) but visibly tag excluded rows with a "not usable" marker
  and a caveat explaining that the data shown is diagnostic only, not a
  suitability signal.
- **Escaping.** Every piece of untrusted text (model/backend identifiers,
  task IDs, notes) that ends up in an SVG ``<title>``/``<text>`` element or
  an HTML attribute goes through :func:`report_style.esc`.
- **Bilingual captions.** All axis labels, legends, and captions use
  :func:`report_style.bi` (DE default-visible, EN via the report's
  language toggle), matching the rest of the report.
- **Accessible palettes/patterns.** Two semantically important
  distinctions -- "not usable" (hard-gate excluded) and "projected/
  estimated" (vs. measured) -- are encoded with a diagonal-hatch SVG
  pattern *in addition to* color (see :func:`_pattern_defs`), so the
  distinction survives grayscale printing and common color-vision
  deficiencies, not just a color legend.
- **Graceful "not enough data".** Every chart returns a short bilingual
  ``<p class="hint">`` instead of raising or rendering an empty/broken SVG
  when its required fields are missing (``None``) or there are no rows to
  plot -- consistent with every other renderer in this package.
"""

