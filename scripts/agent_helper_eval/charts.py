def render_reliability_chart(aggregates: Sequence[AggregateRecord], id_prefix: str = "") -> str:
    """100%-stacked success/error/skipped bar per model-run (by task_count).

    Diagnostic view -- every model-run is shown (errors are themselves
    often the reason for hard-gate exclusion), with excluded rows marked.
    """

    have_counts = [a for a in aggregates if a.task_count > 0]
    excluded = [a for a in have_counts if a.hard_gate_failed]
    if not have_counts:
        return _no_data("Keine Task-Zaehldaten vorhanden.", "No task count data available.")
    ordered = sorted(have_counts, key=lambda a: (a.backend, a.model))
    width = 680
    label_w = 200
    bar_left = label_w
    bar_right = width - 90
    bar_w = bar_right - bar_left
    row_h = 26
    margin_top = 10
    height = margin_top + len(ordered) * row_h + 20
    parts: List[str] = []
    for i, agg in enumerate(ordered):
        y = margin_top + i * row_h
        cy = y + row_h / 2
        parts.append(
            f'<text x="{bar_left - 8}" y="{cy + 4:.1f}" text-anchor="end" font-size="10">{esc(_row_label(agg))}</text>'
        )
        segments = [
            (float(agg.success_count), "#2f855a", f"Success: {agg.success_count}/{agg.task_count}"),
            (float(agg.error_count), "#c53030", f"Error: {agg.error_count}/{agg.task_count}"),
            (
                float(max(0, agg.task_count - agg.success_count - agg.error_count)),
                "#718096",
                f"Skipped/other: {max(0, agg.task_count - agg.success_count - agg.error_count)}/{agg.task_count}",
            ),
        ]
        parts.append(_stacked_segments(bar_left, y + 4, bar_w, row_h - 8, segments))
        parts.append(
            f'<text x="{bar_right + 6}" y="{cy + 4:.1f}" font-size="9">'
            f"{esc(f'{fmt(agg.success_rate_percent)}% ok')}</text>"
        )
    svg = (
        f'<svg class="chart bar-chart" viewBox="0 0 {width} {height}" role="img" '
        f'aria-label="{esc("Zuverlaessigkeit/Fehlerquote je Modell")}">' + "".join(parts) + "</svg>"
    )
    legend = (
        '<ul class="legend-list">'
        '<li><span class="legend-dot" style="background:#2f855a"></span>' + bi("Erfolg", "Success") + "</li>"
        '<li><span class="legend-dot" style="background:#c53030"></span>' + bi("Fehler", "Error") + "</li>"
        '<li><span class="legend-dot" style="background:#718096"></span>'
        + bi("Uebersprungen/Sonstiges", "Skipped/other")
        + "</li>"
        "</ul>"
    )
    return svg + legend + _hard_gate_diagnostic_caveat(excluded)


