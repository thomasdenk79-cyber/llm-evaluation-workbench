# 6. Latency p50/p95/p99
# ---------------------------------------------------------------------------


def render_latency_percentile_chart(
    aggregates: Sequence[AggregateRecord], samples: Sequence[SampleRecord], id_prefix: str = ""
) -> str:
    """Grouped p50/p95/p99 latency bars per usable model-run.

    p50/p95 are read directly from the aggregate record; p99 is computed
    on the fly from this campaign's raw per-sample ``elapsed_seconds``
    values (matched by backend/model/track) via
    :func:`agent_helper_eval.aggregate.percentile` -- no new CSV/schema
    column is introduced for this, since it is only ever needed for this
    chart's display. This is a speed-comparison chart, so hard-gate
    -excluded model-runs are excluded exactly like the quality-vs-speed
    chart, not silently included as if their latency were comparable.
    """

    usable = [a for a in aggregates if not a.hard_gate_failed]
    excluded = [a for a in aggregates if a.hard_gate_failed]
    rows = []
    for agg in usable:
        model_elapsed = [
            s.elapsed_seconds
            for s in samples
            if s.backend == agg.backend and s.model == agg.model and s.track == agg.track
            and s.elapsed_seconds is not None
        ]
        p99 = percentile(model_elapsed, 99) if model_elapsed else None
        if agg.elapsed_seconds_p50 is None and agg.elapsed_seconds_p95 is None and p99 is None:
            continue
        rows.append((agg, p99))
    if not rows:
        return (
            _no_data(
                "Nicht genug Daten fuer Latenz-Perzentile.", "Not enough data for latency percentiles."
            )
            + _excluded_ranking_note(excluded)
        )
    row_labels = [f"{agg.backend}/{agg.model}" for agg, _ in rows]
    p50_values = [agg.elapsed_seconds_p50 for agg, _ in rows]
    p95_values = [agg.elapsed_seconds_p95 for agg, _ in rows]
    p99_values = [p99 for _, p99 in rows]
    chart = _grouped_horizontal_bars(
        row_labels,
        [
            ("P50", p50_values, "#2b6cb0"),
            ("P95", p95_values, "#c05621"),
            ("P99 (berechnet / computed)", p99_values, "#742a2a"),
        ],
        unit="s",
        aria_label="Latenz-Perzentile je Modell / Latency percentiles per model",
    )
    return chart + _excluded_ranking_note(excluded)


