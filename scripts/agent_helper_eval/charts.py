# 16. Historical trend (report-wide, across campaigns)
# ---------------------------------------------------------------------------


def render_historical_trend_chart(campaigns: Sequence["CampaignReportData"], id_prefix: str = "") -> str:
    """Cross-campaign trend: usable-vs-not-usable model-run counts and the
    best usable overall_score, one row per campaign, ordered oldest-first
    (left/top to right/bottom) so the trend reads chronologically.

    This is report-wide (not per-campaign), analogous to the model
    -inventory-feasibility section: it needs the full campaign sequence,
    not just one campaign's data.
    """

    if not campaigns:
        return _no_data("Keine Kampagnen fuer den Verlauf vorhanden.", "No campaigns available for the trend.")
    ordered = sorted(campaigns, key=lambda c: c.generated_at)
    width = 680
    label_w = 220
    bar_left = label_w
    bar_right = width - 90
    bar_w = bar_right - bar_left
    row_h = 30
    margin_top = 10
    height = margin_top + len(ordered) * row_h + 20
    parts: List[str] = []
    best_scores: List[Optional[float]] = []
    for i, campaign in enumerate(ordered):
        usable = [a for a in campaign.aggregates if not a.hard_gate_failed]
        excluded = [a for a in campaign.aggregates if a.hard_gate_failed]
        best = max((a.overall_score for a in usable if a.overall_score is not None), default=None)
        best_scores.append(best)
        total = len(usable) + len(excluded)
        y = margin_top + i * row_h
        cy = y + row_h / 2
        label = f"{campaign.campaign_id} ({campaign.generated_at[:10]})"
        parts.append(
            f'<text x="{bar_left - 8}" y="{cy + 4:.1f}" text-anchor="end" font-size="10">{esc(label)}</text>'
        )
        if total > 0:
            segments = [
                (float(len(usable)), TIER_COLORS["tier-1-recommended"], f"Usable: {len(usable)}/{total}"),
                (float(len(excluded)), TIER_COLORS["not-usable"], f"Not usable: {len(excluded)}/{total}"),
            ]
            parts.append(_stacked_segments(bar_left, y + 6, bar_w, row_h - 12, segments))
        best_text = fmt(best) if best is not None else NA
        parts.append(
            f'<text x="{bar_right + 6}" y="{cy + 4:.1f}" font-size="9">{esc(f"best={best_text}")}</text>'
        )
    svg = (
        f'<svg class="chart bar-chart" viewBox="0 0 {width} {height}" role="img" '
        f'aria-label="{esc("Verlauf ueber Kampagnen: nutzbar vs. nicht nutzbar, bester nutzbarer Score")}">'
        + "".join(parts)
        + "</svg>"
    )
    legend = (
        '<ul class="legend-list">'
        f'<li><span class="legend-dot" style="background:{TIER_COLORS["tier-1-recommended"]}"></span>{bi("Nutzbar", "Usable")}</li>'
        f'<li><span class="legend-dot" style="background:{TIER_COLORS["not-usable"]}"></span>{bi("Nicht nutzbar", "Not usable")}</li>'
        "</ul>"
    )
    caveat = (
        f'<p class="hint">{bi("Sortiert vom aeltesten zum neuesten Lauf (chronologisch). \'best\' ist der beste NUTZBARE Gesamt-Score dieser Kampagne (nach dem harten Akzeptanz-Gate), niemals ein ausgeschlossenes Modell.", "Sorted oldest to newest (chronological). \'best\' is the best USABLE overall score for that campaign (after the hard acceptance gate), never an excluded model.")}</p>'
    )
    return svg + legend + caveat
