def _score_color(score: float) -> str:
    if score >= 90:
        return "#22543d"
    if score >= 75:
        return "#2f855a"
    if score >= 60:
        return "#68a063"
    return "#c05621"


def render_task_model_heatmap(samples: Sequence[SampleRecord], id_prefix: str = "") -> str:
    """Task-id x model grid, colored by the *final* attempt's outcome.

    "Final attempt" = the sample with the highest ``iteration_index`` (tie
    -broken by ``retry_count`` then ``sample_seq``) for that
    (task_id, backend/model) pair -- representing what the orchestrator
    would actually have accepted or rejected after any retries/iterations.
    A cell whose final attempt is ``not_usable`` is always rendered with
    the diagonal-hatch "not usable" pattern *regardless of its raw
    composite_score*, so a not-usable sample can never look like a merely
    mediocre-but-usable one in the grid.
    """

    if not samples:
        return _no_data(
            "Keine Sample-Daten fuer die Task/Modell-Heatmap vorhanden.",
            "No sample data available for the task/model heatmap.",
        )
    cells: dict = {}
    for s in samples:
        key = (s.task_id, f"{s.backend}/{s.model}")
        cur = cells.get(key)
        rank = (s.iteration_index, s.retry_count, s.sample_seq)
        if cur is None or rank > cur[0]:
            cells[key] = (rank, s)
    task_ids = sorted({s.task_id for s in samples})
    models = sorted({f"{s.backend}/{s.model}" for s in samples})
    if not task_ids or not models:
        return _no_data(
            "Keine Sample-Daten fuer die Task/Modell-Heatmap vorhanden.",
            "No sample data available for the task/model heatmap.",
        )

    cell_w, cell_h = 92, 26
    label_col_w = 180
    header_h = 96
    width = label_col_w + cell_w * len(models) + 20
    height = header_h + cell_h * len(task_ids) + 10
    defs, notusable_fill, _ = _pattern_defs(f"{id_prefix}-heatmap")

    parts: List[str] = [defs]
    for j, model in enumerate(models):
        x = label_col_w + j * cell_w + cell_w / 2
        parts.append(
            f'<text x="{x:.1f}" y="{header_h - 6}" text-anchor="start" font-size="10" '
            f'transform="rotate(-40 {x:.1f} {header_h - 6})">{esc(model)}</text>'
        )
    for i, task_id in enumerate(task_ids):
        y = header_h + i * cell_h
        parts.append(
            f'<text x="{label_col_w - 8}" y="{y + cell_h / 2 + 4:.1f}" text-anchor="end" font-size="10">{esc(task_id)}</text>'
        )
        for j, model in enumerate(models):
            x = label_col_w + j * cell_w
            entry = cells.get((task_id, model))
            text = ""
            if entry is None:
                fill = "#e2e8f0"
                title = f"{task_id} / {model}: no data / keine Daten"
            else:
                _, s = entry
                if s.acceptance_status == "not_usable":
                    fill = notusable_fill
                elif s.acceptance_status == "accepted":
                    fill = _score_color(s.composite_score if s.composite_score is not None else 0.0)
                    text = fmt(s.composite_score, 0) if s.composite_score is not None else NA
                else:
                    fill = "#a0aec0"
                title = (
                    f"{task_id} / {model}: status={s.status} acceptance={s.acceptance_status} "
                    f"score={fmt(s.composite_score)} elapsed={fmt(s.elapsed_seconds)}s "
                    f"retry={s.retry_count} iter={s.iteration_index}"
                )
            parts.append(
                f'<rect x="{x:.1f}" y="{y:.1f}" width="{cell_w - 2}" height="{cell_h - 2}" fill="{fill}" '
                f'stroke="#ffffff"><title>{esc(title)}</title></rect>'
            )
            if text:
                parts.append(
                    f'<text x="{x + cell_w / 2 - 1:.1f}" y="{y + cell_h / 2 + 3:.1f}" text-anchor="middle" '
                    f'font-size="10" fill="#ffffff">{esc(text)}</text>'
                )
    svg = (
        f'<svg class="chart heatmap-chart" viewBox="0 0 {width} {height}" role="img" '
        f'aria-label="{esc("Task-Qualitaet je Modell (letzter Versuch)")}">' + "".join(parts) + "</svg>"
    )
    legend = (
        '<ul class="legend-list">'
        f'<li><span class="legend-dot" style="background:{_score_color(95)}"></span>{bi("Akzeptiert, hoher Score", "Accepted, high score")}</li>'
        f'<li><span class="legend-dot" style="background:{_score_color(65)}"></span>{bi("Akzeptiert, niedrigerer Score", "Accepted, lower score")}</li>'
        '<li><span class="legend-dot" style="background:repeating-linear-gradient(45deg,'
        f'{TIER_COLORS["not-usable"]},{TIER_COLORS["not-usable"]} 2px,#fff 2px,#fff 4px)"></span>'
        f'{bi("Nicht nutzbar (letzter Versuch)", "Not usable (final attempt)")}</li>'
        f'<li><span class="legend-dot" style="background:#a0aec0"></span>{bi("Nicht bewertet", "Not evaluated")}</li>'
        f'<li><span class="legend-dot" style="background:#e2e8f0"></span>{bi("Keine Daten fuer diese Kombination", "No data for this combination")}</li>'
        "</ul>"
    )
    return svg + legend


