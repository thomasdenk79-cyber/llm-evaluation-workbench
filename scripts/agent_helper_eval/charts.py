# A small, fixed, colorblind-considered categorical palette for series that
# are not tier-colored (phase categories, providers, per-model lines in the
# concurrency chart). Deliberately distinct hues + one dashed/pattern
# variant is layered on top where two categories could otherwise only be
# told apart by hue (see ``_pattern_defs``).
_PALETTE = ["#2b6cb0", "#2f855a", "#805ad5", "#c05621", "#00838f", "#b83280", "#5a67d8"]


def _mean(values: Sequence[Optional[float]]) -> Optional[float]:
    clean = [v for v in values if v is not None]
    if not clean:
        return None
    return sum(clean) / len(clean)


def _no_data(de: str, en: str) -> str:
    return f'<p class="hint">{bi(de, en)}</p>'


def _safe_id(text: str) -> str:
    """Sanitize a string for use as (part of) an XML/SVG element id.

    ``id_prefix`` values are always internally generated by ``report.py``
    (e.g. ``"c0"``), never raw untrusted model output, but this is cheap
    defense in depth against an id that would otherwise produce invalid
    SVG markup (e.g. containing ``"`` or whitespace).
    """

    cleaned = re.sub(r"[^A-Za-z0-9_-]", "-", text or "")
    return cleaned or "x"


def _pattern_defs(id_prefix: str) -> Tuple[str, str, str]:
    """Return ``(defs_markup, notusable_fill_url, projection_fill_url)``.

    Both patterns encode their meaning in *shape*, not only color, so the
    not-usable/projection distinction survives grayscale printing and
    common color-vision deficiencies: "not usable" is a steep, solid
    diagonal hatch on a dark-red ground; "projection/estimate" is a
    shallower *dashed* diagonal hatch on an amber ground -- visibly
    different patterns, not just different hues.
    """

    safe = _safe_id(id_prefix)
    notusable_id = f"hatch-notusable-{safe}"
    projection_id = f"hatch-projection-{safe}"
    defs = (
        "<defs>"
        f'<pattern id="{notusable_id}" width="6" height="6" patternUnits="userSpaceOnUse" patternTransform="rotate(45)">'
        f'<rect width="6" height="6" fill="{TIER_COLORS["not-usable"]}"/>'
        '<line x1="0" y1="0" x2="0" y2="6" stroke="#ffffff" stroke-width="2.2"/>'
        "</pattern>"
        f'<pattern id="{projection_id}" width="8" height="8" patternUnits="userSpaceOnUse" patternTransform="rotate(45)">'
        f'<rect width="8" height="8" fill="{TIER_COLORS["tier-2-conditional"]}"/>'
        '<line x1="0" y1="0" x2="0" y2="8" stroke="#ffffff" stroke-width="1.6" stroke-dasharray="2,2"/>'
        "</pattern>"
        "</defs>"
    )
    return defs, f"url(#{notusable_id})", f"url(#{projection_id})"


def _excluded_ranking_note(excluded: Sequence[AggregateRecord]) -> str:
    """Shared "not plotted -- EXCLUDED" note for every ranking/comparison
    chart (quality-vs-speed, latency percentiles, time-to-accepted-result,
    routing/cost-tier scenario). Deliberately worded to make clear this is
    a quality/safety verdict, never a data-availability gap.
    """

    if not excluded:
        return ""
    names = ", ".join(esc(f"{a.backend}/{a.model} [{a.track}]") for a in excluded)
    return (
        f'<p class="hint hint-warning">{bi("Nicht dargestellt -- AUSGESCHLOSSEN (nicht nutzbar, unabhaengig von Geschwindigkeit):", "Not plotted -- EXCLUDED (not usable, regardless of speed):")} {names}</p>'
    )


def _hard_gate_diagnostic_caveat(excluded: Sequence[AggregateRecord]) -> str:
    """Shared caveat for diagnostic/resource charts that -- unlike the
    ranking charts above -- intentionally still plot hard-gate-excluded
    model-runs (matching the pre-existing resource/phase-timing tables,
    which are diagnostic views, not rankings). Every such chart marks
    excluded rows with a "⚠" suffix in the row label; this caveat explains
    what that marker means right below the chart.
    """

    if not excluded:
        return ""
    names = ", ".join(esc(f"{a.backend}/{a.model} [{a.track}]") for a in excluded)
    return (
        f'<p class="hint hint-warning">{bi(f"Hinweis: Mit \u26a0 markierte Modelle ({names}) haben das harte Akzeptanz-Gate nicht bestanden (NICHT NUTZBAR). Diese Ressourcen-/Diagnosedaten sind KEIN Eignungsnachweis, sondern rein informativ.", f"Note: models marked \u26a0 ({names}) failed the hard acceptance gate (NOT USABLE). This resource/diagnostic data is NOT a suitability signal, informational only.")}</p>'
    )


def _row_label(agg: AggregateRecord) -> str:
    label = f"{agg.backend}/{agg.model}"
    return f"{label} \u26a0" if agg.hard_gate_failed else label


