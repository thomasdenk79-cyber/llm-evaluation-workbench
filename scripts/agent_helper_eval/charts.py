# ---------------------------------------------------------------------------
# 11. Concurrency scaling (1/2/4)
# ---------------------------------------------------------------------------


def render_concurrency_scaling_chart(
    capacity_profiles: Sequence[CapacityProfileRecord], id_prefix: str = ""
) -> str:
    """Line chart of aggregate/per-request tokens/sec across concurrency
    levels for every (backend, model) that has a capacity profile.

    Every row in ``capacity_profiles`` is schema-guaranteed to already have
    passed the hard acceptance gate and an explicit memory-safety check at
    concurrency=1 (see ``schema.validate_capacity_profile`` and
    ``capacity_profile.can_start_concurrency_profile``), so no additional
    exclusion filtering is needed here -- unlike the ranking charts above.
    """

    if not capacity_profiles:
        return _no_data(
            "Kein Kapazitaets-/Nebenlaeufigkeitsprofil vorhanden.",
            "No capacity/concurrency profile available.",
        )
    groups: dict = {}
    for cp in capacity_profiles:
        groups.setdefault((cp.backend, cp.model), []).append(cp)
    width, height = 640, 320
    margin_left, margin_right, margin_top, margin_bottom = 60, 20, 20, 46
    plot_w = width - margin_left - margin_right
    plot_h = height - margin_top - margin_bottom
    levels = sorted({cp.concurrency_level for cp in capacity_profiles})
    if len(levels) < 1:
        return _no_data(
            "Kein Kapazitaets-/Nebenlaeufigkeitsprofil vorhanden.",
            "No capacity/concurrency profile available.",
        )

    def x_pos(level: int) -> float:
        if len(levels) == 1:
            return margin_left + plot_w / 2
        idx = levels.index(level)
        return margin_left + plot_w * idx / (len(levels) - 1)

    all_tps = [cp.aggregate_tokens_per_second for cp in capacity_profiles if cp.aggregate_tokens_per_second]
    all_tps += [
        cp.per_request_tokens_per_second_mean
        for cp in capacity_profiles
        if cp.per_request_tokens_per_second_mean
    ]
    y_max = max(all_tps) * 1.1 if all_tps else 1.0

    def y_pos(value: float) -> float:
        return margin_top + plot_h * (1 - value / y_max)

    grid = []
    for level in levels:
        x = x_pos(level)
        grid.append(
            f'<line class="gridline" x1="{x:.1f}" y1="{margin_top}" x2="{x:.1f}" y2="{height - margin_bottom}"/>'
            f'<text x="{x:.1f}" y="{height - margin_bottom + 16}" text-anchor="middle">{level}</text>'
        )
    axis_x = (
        f'<line class="axis" x1="{margin_left}" y1="{height - margin_bottom}" '
        f'x2="{width - margin_right}" y2="{height - margin_bottom}"/>'
    )
